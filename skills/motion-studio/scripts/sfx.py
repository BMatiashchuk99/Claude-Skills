#!/usr/bin/env python3
"""Sound effects and a background music bed, synthesized from scratch.

Everything here is generated by code, so it is free of copyright and needs no
downloads. Drop your own files into <project>/assets/sfx/<name>.wav to replace
any effect, or set "music": {"file": "assets/music.mp3"} in the storyboard.

Usage: python3 sfx.py <project_dir>
"""
import math
import random
import sys
import wave
from array import array
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import load_json, log, run  # noqa: E402

SR = 48000


def write_wav(path, samples, sr=SR):
    peak = max(1e-9, max(abs(s) for s in samples))
    k = 0.89 / peak
    data = array("h", (int(max(-1.0, min(1.0, s * k)) * 32767) for s in samples))
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes(data.tobytes())


def lp_coef(fc, sr=SR):
    return 1.0 - math.exp(-2.0 * math.pi * max(10.0, fc) / sr)


def whoosh(dur=0.62, peak=0.28, lo=250, hi=5200, seed=1):
    rnd = random.Random(seed)
    n = int(dur * SR)
    out, y1, y2 = [], 0.0, 0.0
    for i in range(n):
        t = i / SR
        env = (t / peak) ** 2.2 if t < peak else ((dur - t) / (dur - peak)) ** 1.6
        fc = lo + (hi - lo) * env
        x = rnd.uniform(-1, 1)
        y1 += lp_coef(fc) * (x - y1)
        y2 += lp_coef(fc * 0.22) * (y1 - y2)
        out.append((y1 - y2) * env)
    return out


def pop(dur=0.12):
    out, ph = [], 0.0
    for i in range(int(dur * SR)):
        t = i / SR
        f = 300 + 700 * math.exp(-t * 45)
        ph += 2 * math.pi * f / SR
        out.append(math.sin(ph) * math.exp(-t * 32) * min(1, t * 2000))
    return out


def click(dur=0.06):
    rnd = random.Random(7)
    out, ph = [], 0.0
    for i in range(int(dur * SR)):
        t = i / SR
        ph += 2 * math.pi * 2100 / SR
        out.append(0.6 * math.sin(ph) * math.exp(-t * 140) + rnd.uniform(-1, 1) * math.exp(-t * 900))
    return out


def tick(dur=0.025):
    rnd = random.Random(3)
    return [rnd.uniform(-1, 1) * math.exp(-(i / SR) * 600) for i in range(int(dur * SR))]


def impact(dur=1.0):
    rnd = random.Random(11)
    out, ph, y = [], 0.0, 0.0
    for i in range(int(dur * SR)):
        t = i / SR
        f = 38 + 40 * math.exp(-t * 12)
        ph += 2 * math.pi * f / SR
        body = math.sin(ph) * math.exp(-t * 3.6)
        y += lp_coef(1800) * (rnd.uniform(-1, 1) - y)
        out.append(math.tanh(1.8 * (body + 0.9 * y * math.exp(-t * 20))))
    return out


def riser(dur=1.2):
    rnd = random.Random(5)
    out, ph, y1, y2 = [], 0.0, 0.0, 0.0
    for i in range(int(dur * SR)):
        t = i / SR
        p = t / dur
        f = 180 * (1 + 6 * p * p)
        ph += 2 * math.pi * f / SR
        y1 += lp_coef(400 + 7000 * p) * (rnd.uniform(-1, 1) - y1)
        y2 += lp_coef(200 + 1500 * p) * (y1 - y2)
        env = p ** 1.8 * (1 if p < 0.94 else (1 - p) / 0.06)
        out.append(env * (0.5 * math.sin(ph) + 0.25 * math.sin(2 * ph) + 0.9 * (y1 - y2)))
    return out


def ding(dur=1.3):
    out = []
    for i in range(int(dur * SR)):
        t = i / SR
        a = min(1, t * 400)
        s = (math.sin(2 * math.pi * 1318.5 * t) + 0.35 * math.sin(2 * math.pi * 2637 * t) * math.exp(-t * 3)
             + 0.12 * math.sin(2 * math.pi * 3956 * t) * math.exp(-t * 6))
        out.append(a * s * math.exp(-t * 4.2))
    return out


def cue_file(cue):
    """File name for a cue; risers are rendered to the exact length they need."""
    if cue["name"] == "riser" and cue.get("dur"):
        return f"riser_{int(float(cue['dur']) * 1000)}.wav"
    return f"{cue['name']}.wav"


LIBRARY = {
    "whoosh": lambda: whoosh(),
    "whoosh2": lambda: whoosh(dur=0.7, peak=0.3, lo=180, hi=3800, seed=2),
    "pop": pop, "click": click, "tick": tick, "impact": impact, "riser": riser, "ding": ding,
}


# ------------------------------ music ------------------------------
MSR = 22050
NOTE = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6, "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}


def hz(name, octave):
    return 440.0 * 2 ** ((NOTE[name] + 12 * (octave + 1) - 69) / 12)


CHORDS = [("A", ["A", "C", "E"]), ("F", ["F", "A", "C"]), ("C", ["C", "E", "G"]), ("G", ["G", "B", "D"])]


def music_loop(style="pulse", bpm=112):
    beat = 60.0 / bpm
    bar = beat * 4
    chord_len = bar * 2
    total = chord_len * len(CHORDS)
    n = int(total * MSR)
    buf = [0.0] * n
    rnd = random.Random(42)

    def add(start, length, fn, gain):
        a = int(start * MSR)
        b = min(n, a + int(length * MSR))
        for i in range(a, b):
            buf[i] += gain * fn((i - a) / MSR)

    for ci, (root, tones) in enumerate(CHORDS):
        c0 = ci * chord_len
        freqs = [hz(t, 3 if t in ("A", "B", "G") and root in ("A", "G") else 4) for t in tones]
        # pad: detuned sines with slow swell
        for f in freqs:
            for det in (-0.12, 0.12):
                ff = f * (1 + det / 100 * 3)
                add(c0, chord_len, lambda t, ff=ff: math.sin(2 * math.pi * ff * t) * min(1, t / 0.9) * min(1, (chord_len - t) / 0.4), 0.05)
        rf = hz(root, 2)
        if style == "pulse":
            # eighth-note bass pluck
            for k in range(16):
                st = c0 + k * beat / 2
                add(st, beat / 2, lambda t: (math.sin(2 * math.pi * rf * t) + 0.3 * math.sin(4 * math.pi * rf * t)) * math.exp(-t * 7), 0.16)
            # sixteenth arp, quiet
            arp = freqs + [freqs[0] * 2]
            for k in range(32):
                st = c0 + k * beat / 4
                f = arp[k % 4] * 2
                add(st, beat / 2, lambda t, f=f: math.sin(2 * math.pi * f * t) * math.exp(-t * 14), 0.035)
            # soft kick on 1 and 3, hat on off-beats
            for k in range(8):
                kb = c0 + k * beat
                if k % 2 == 0:
                    add(kb, 0.3, lambda t: math.sin(2 * math.pi * (50 + 90 * math.exp(-t * 30)) * t) * math.exp(-t * 11), 0.32)
                add(kb + beat / 2, 0.05, lambda t: rnd.uniform(-1, 1) * math.exp(-t * 90), 0.025)
        else:
            add(c0, chord_len, lambda t: math.sin(2 * math.pi * rf * t) * min(1, t / 1.2) * min(1, (chord_len - t) / 0.5), 0.12)
    return buf, total


def build_music(cfg, out_wav, build):
    style = cfg.get("generate", "pulse") if isinstance(cfg, dict) else "pulse"
    raw = build / f"music_{style}_raw.wav"
    if not raw.exists():
        buf, _ = music_loop(style if style in ("pulse", "pad") else "pulse")
        write_wav(raw, buf, MSR)
    run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(raw),
         "-af", "aresample=48000,aecho=0.8:0.6:120|240:0.25|0.15,lowpass=f=9000,highpass=f=35",
         "-ac", "2", str(out_wav)])


def main(project):
    project = Path(project).resolve()
    build = project / "build"
    tl = load_json(build / "timeline.json")
    sdir = build / "sfx"
    sdir.mkdir(parents=True, exist_ok=True)
    cues = tl.get("sfx", [])
    needed = {c["name"] for c in cues}
    custom_dir = project / "assets" / "sfx"
    for cue in cues:
        name = cue["name"]
        dst = sdir / cue_file(cue)
        customs = sorted(custom_dir.glob(f"{name}.*")) if custom_dir.exists() else []
        if customs:
            run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(customs[0]), "-ac", "1", "-ar", str(SR), str(dst)])
        elif not dst.exists():
            if name == "riser" and cue.get("dur"):
                write_wav(dst, riser(max(0.3, float(cue["dur"]))))
            elif name in LIBRARY:
                write_wav(dst, LIBRARY[name]())
            else:
                log(f"sfx '{name}' unknown and no assets/sfx/{name}.wav, skipping")
    music = tl.get("music")
    if music and music != "none" and not (isinstance(music, dict) and music.get("file")):
        dst = build / "music.wav"
        build_music(music, dst, build)
        log("music  generated bed (replace with \"music\": {\"file\": \"assets/your-track.mp3\"})")
    log(f"sfx    {len(needed)} effect(s) ready")


if __name__ == "__main__":
    main(sys.argv[1])
